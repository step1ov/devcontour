import { createHash } from 'node:crypto';

// Почему таксономия, а не разбор текста постфактум.
//
// Причина отказа известна ровно там, где отказ возник: пустой коммит виден по
// diff, провал проверки — по её коду выхода, отказ ревью — по его вердикту.
// Восстанавливать этот факт регулярным выражением по сообщению значит
// выбросить знание и потом угадывать его — а угадывание ошибается там, где
// текст задачи похож на текст инфраструктуры. Поэтому класс ставится в точке
// отказа, записывается вместе с попыткой и дальше используется как есть.

export const failureKinds = [
  /** Провайдер отказал всем: нет кредитов, runtime не авторизован. */
  'provider-auth',
  /** Окружение не дало работать: runtime не стартовал, транспорт оборвался. */
  'environment',
  /** Попытка исчерпала отведённое ей время. */
  'timeout',
  /** База прогонов отстала от рабочей ветки: дерево без подготовки. */
  'stale-base',
  /** Отчёт «сделано» без единого изменения. */
  'empty-result',
  /** Изменено за пределами области задачи или защищённые файлы. */
  'scope-violation',
  /** Настроенная проверка не прошла. */
  'gate',
  /** Независимое ревью отклонило результат. */
  'review',
  /** Слияние с веткой интеграции не сошлось. */
  'merge',
  /** Остановлено человеком. */
  'cancelled',
  /** Класс неизвестен: восстанавливать вслепую нельзя. */
  'unknown',
] as const;
export type FailureKind = (typeof failureKinds)[number];

/** Отказ с известным классом. Класс ставит тот, кто отказ обнаружил. */
export class TaskFailure extends Error {
  constructor(
    readonly kind: FailureKind,
    message: string,
  ) {
    super(message);
    this.name = 'TaskFailure';
  }
}

/**
 * Отпечаток отказа: одинаковые сбои должны совпадать, разные — расходиться.
 *
 * Из сообщения убирается всё, что меняется от попытки к попытке, — SHA, id
 * прогонов, пути с временными каталогами, числа, время. Иначе два одинаковых
 * провала одной проверки выглядели бы как два разных, и предел одинаковых
 * повторов не сработал бы ни разу.
 */
export function failureFingerprint(kind: FailureKind, message: string) {
  const normalized = message
    .toLowerCase()
    // UUID раньше SHA: шаблон SHA съедает его восьми- и двенадцатисимвольные
    // группы, после чего целого UUID уже не видно, а середина остаётся
    // случайной — и один и тот же отказ с новым request id считался разным.
    .replace(/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/g, '<id>')
    .replace(/\b[0-9a-f]{7,40}\b/g, '<sha>')
    .replace(/\d{4}-\d{2}-\d{2}t[\d:.]+z?/g, '<time>')
    .replace(/\/[^\s'"]*\/[^\s'"]*/g, '<path>')
    .replace(/\d+/g, '<n>')
    .replace(/\s+/g, ' ')
    .trim()
    // Предел выше всей диагностики проверки (оба потока и упавшие testcases,
    // каждое со своим лимитом): при прежних 300 символах ошибка stderr
    // оказывалась за пределом, и разные провалы получали один отпечаток.
    .slice(0, 2000);
  return createHash('sha256')
    .update(kind + '\n' + normalized)
    .digest('hex')
    .slice(0, 16);
}

export interface RepairRule {
  /** `retry` — новая попытка той же задачи; `stop` — звать человека. */
  action: 'retry' | 'stop';
  /**
   * Сколько раз один и тот же отпечаток разрешено чинить автоматически.
   * Исчерпан — гипотез больше нет, и цикл останавливается с этой причиной.
   */
  repeats: number;
  /** Причина, которую увидит человек, когда цикл остановится. */
  explain: string;
  /**
   * Отказ повторится на любой задаче, а не только на этой: выдача
   * останавливается целиком, иначе очередь переберёт задачи одну за другой и
   * сожжёт бюджет попыток каждой на одной и той же внешней причине.
   *
   * Этим же свойством причина снимается: починив её, восстановление убирает
   * свою запись из списка блокировок, а выдача возвращается, только когда не
   * осталось ни одной. Решать это по тексту сообщения нельзя — замечание
   * ревью про «401 Unauthorized» в разрабатываемом приложении так становилось
   * отказом провайдера и останавливало работу насовсем.
   */
  blocksQueue?: boolean;
}

